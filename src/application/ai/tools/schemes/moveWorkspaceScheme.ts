export const moveWorkspaceScheme = `
'move_workspace(id: str, before_workspace_id: str = None, after_workspace_id: str = None) -> None'

- **Arguments:**
  - 'id': ID of the workspace to move.
  - 'before_workspace_id': ID of the workspace that should be immediately after the moved workspace.
  - 'after_workspace_id': ID of the workspace that should be immediately before the moved workspace.
`
