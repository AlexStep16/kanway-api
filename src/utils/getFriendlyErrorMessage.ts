export function getFriendlyErrorMessage(error: any): string {
  const msg = (error?.message || '').toLowerCase()
  const status = error?.status || error?.response?.status

  // --- Критические ошибки инфраструктуры (скрываем от юзера) ---
  if (status === 401 || status === 403) {
    // Неверный токен или доступ запрещен
    return 'В данный момент сервис испытывает технические трудности. Мы уже работаем над исправлением.'
  }

  if (status === 402) {
    // Закончился баланс (Insufficient Quota)
    return 'Сервис временно недоступен. Пожалуйста, попробуйте позже.'
  }

  // --- Ошибки нагрузки и сети (можно сказать мягко) ---
  if (status === 429) {
    return 'Сейчас очень высокая нагрузка на сервис. Пожалуйста, подождите минутку и попробуйте снова.'
  }

  if (status >= 500) {
    return 'Произошла ошибка на стороне AI-провайдера. Попробуйте повторить запрос через пару минут.'
  }

  if (msg.includes('timeout') || msg.includes('etimedout')) {
    return 'Ответ занимает слишком много времени. Попробуйте упростить запрос.'
  }

  // --- Ошибки безопасности / Политики контента ---
  if (status === 400 && (msg.includes('content_filter') || msg.includes('safety'))) {
    return 'Ваш запрос не может быть обработан из-за политики безопасности.'
  }

  // --- Дефолтная заглушка ---
  // Если ошибка совсем непонятная (код упал), пишем общую фразу
  return 'Произошла непредвиденная ошибка при генерации ответа. Попробуйте еще раз.'
}
